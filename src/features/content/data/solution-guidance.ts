export function getSolutionGuidance(path: string) {
  const source = solutions.find((page) => page.path === path);
  const content = source?.text ? guidance[source.id] : undefined;
  return source && content
    ? { summary: content[0], preparation: content[1], sourceUrl: source.sourceUrl }
    : undefined;
}
